function t(key) {
  const lang = currentLang();
  return I18N[lang][key] || I18N.ko[key] || key;
}

function currentLang() {
  return document.documentElement.getAttribute("data-lang") === "en" ? "en" : "ko";
}

function currentTheme() {
  return document.documentElement.getAttribute("data-theme") === "dark" ? "dark" : "light";
}

function applyI18n() {
  const lang = currentLang();
  document.documentElement.lang = lang;
  document.title = t("title");
  const desc = document.querySelector('meta[name="description"]');
  if (desc) {
    desc.setAttribute("content", t("desc"));
  }
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  langToggle.textContent = lang === "ko" ? "EN" : "한글";
  langToggle.setAttribute("aria-label", lang === "ko" ? I18N.ko["lang.toEn"] : I18N.en["lang.toEn"]);
  setTheme(currentTheme());
  typeMotto();
  renderGuests();
}

function setLang(lang) {
  document.documentElement.setAttribute("data-lang", lang);
  localStorage.setItem("lang", lang);
  applyI18n();
}

function setTheme(theme) {
  document.documentElement.setAttribute("data-theme", theme);
  localStorage.setItem("theme", theme);
  themeToggle.setAttribute("aria-label", theme === "dark" ? t("theme.toLight") : t("theme.toDark"));
}

function setHeaderState() {
  header.classList.toggle("is-scrolled", window.scrollY > 12);
}

function setToTopState() {
  toTop.classList.toggle("is-on", window.scrollY > 420);
}

function setProgress() {
  const max = document.documentElement.scrollHeight - window.innerHeight;
  const ratio = max > 0 ? window.scrollY / max : 0;
  progressFill.style.width = `${Math.min(100, Math.max(0, ratio * 100))}%`;
}

function setParallax() {
  if (reduceMotion || !mottoInner) {
    return;
  }
  const rect = mottoSection.getBoundingClientRect();
  const mid = rect.top + rect.height / 2 - window.innerHeight / 2;
  mottoInner.style.transform = `translateY(${Math.round(mid * -0.14)}px)`;
}

function onScroll() {
  setHeaderState();
  setToTopState();
  setProgress();
  setParallax();
}

